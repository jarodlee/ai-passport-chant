#!/usr/bin/env python3
"""Generate small uncompressed 4bpp LVGL fonts; requires Pillow (FreeType)."""
from pathlib import Path
import re
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
source = "".join(p.read_text() for p in (ROOT / "main").glob("chant_*.c"))
body_chars = sorted(set(chr(i) for i in range(32, 127)) | set(re.findall(r"[\u3400-\u9fff]", source)))
# Derive the large-font inventory from actual headings and home labels, rather
# than a hand-maintained list that can silently omit a newly added page title.
title_text='▶◀' + ''.join(re.findall(r'\btitle\s*=\s*"([^"]*)"',source))
title_text+=''.join(re.findall(r'\{"([^"]+)",PAGE_',source))
title_text+=''.join(json.loads(p.read_text())['title'] for p in (ROOT/'assets/music').glob('*-metadata.json'))
title_chars=sorted(set(chr(i) for i in range(32,127)) | set(title_text))
(ROOT / "main/chant_font_inventory.h").write_text('#pragma once\n' +
    '#define CHANT_UI_INVENTORY "' + ''.join(c for c in body_chars if ord(c)>127) + ' ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789%:/ .->"\n' +
    '#define CHANT_TITLE_INVENTORY "' + ''.join(c for c in title_chars if ord(c)>127) + ' ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789%:/ .->"\n')
font_root = ROOT / "assets/fonts"
(font_root / "chant-glyphs.txt").write_text("".join(body_chars) + "\n")

(font_root / "chant-title-glyphs.txt").write_text("".join(title_chars)+"\n")
for size in (18, 28):
    chars=body_chars if size==18 else title_chars
    font = ImageFont.truetype(str(font_root / "NotoSansCJKsc-Regular.otf"), size)
    bitmap = bytearray()
    descriptors = ["{0}"]
    expected = []
    for char in chars:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right-left, bottom-top
        if char == ' ':
            width = height = 0
        image = Image.new("L", (max(1,width), max(1,height)))
        ImageDraw.Draw(image).text((-left,-top), char, font=font, fill=255, anchor="ls")
        pixels = [round(x/17) for x in image.getdata()] if width and height else []
        offset = len(bitmap)
        for i in range(0,len(pixels),2):
            bitmap.append((pixels[i]<<4) | (pixels[i+1] if i+1<len(pixels) else 0))
        expected.append((offset,pixels))
        descriptors.append("{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}" %
                           (offset, round(font.getlength(char)*16),width,height,left,-bottom))
    name = f"chant_font_{size}"
    hexes = ','.join(f'0x{x:02x}' for x in bitmap)
    offsets = ','.join(str(ord(c)-32) for c in chars)
    code = f'''// Generated by tools/generate_chant_fonts.py from Noto Sans CJK (SIL OFL).
#include "lvgl.h"
static const uint8_t bitmap[] = {{{hexes}}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{{','.join(descriptors)}}};
static const uint16_t unicode_list[] = {{{offsets}}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
 {{.range_start=32,.range_length={ord(chars[-1])-31},.glyph_id_start=1,
   .unicode_list=unicode_list,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}
}};
static lv_font_fmt_txt_dsc_t descriptor = {{
 .glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=4,.bitmap_format=0
}};
const lv_font_t {name} = {{
 .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
 .line_height={size+8},.base_line=7,.dsc=&descriptor
}};
'''
    dest = font_root / (name+'.c');dest.write_text(code)
    actual = bytes(int(x,16) for x in re.findall(r'0x[0-9a-f]{2}',dest.read_text()))
    for offset,pixels in expected:
        for i,pixel in enumerate(pixels):
            byte = actual[offset+i//2]
            assert ((byte>>4) if i%2==0 else (byte&15)) == pixel
    print(name, len(chars),'glyphs,',len(bitmap),'bytes; pixel readback PASS')
